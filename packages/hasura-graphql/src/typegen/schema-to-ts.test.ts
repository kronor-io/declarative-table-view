import { describe, it, expect } from '@jest/globals';
import { buildSchema } from 'graphql';
import { collectReachableTypes, referencedTypeNames, renderTsFromSchema, renderTypeModule } from './schema-to-ts.js';

describe('cli/typegen/schemaToTs', () => {
    it('renders object types with correct nullability and scalar mapping', () => {
        const schema = buildSchema(`
            type Query {
                paymentRequests: [PaymentRequest!]!
            }

            scalar CustomScalar

            type PaymentRequest {
                id: ID!
                amount: Int!
                customer: Customer
                custom: CustomScalar!
            }

            type Customer {
                email: String!
            }
        `);

        const root = schema.getType('PaymentRequest');
        if (!root || Array.isArray(root)) throw new Error('Missing PaymentRequest type');

        const types = collectReachableTypes(schema, [root as any]);
        const tsOut = renderTsFromSchema(types, {
            includeGraphqlTypeComments: true
        });

        const tsOutLocal = renderTsFromSchema(types, {
            exportTypes: false
        });

        expect(tsOut).toContain('export type PaymentRequest');
        expect(tsOutLocal).toContain('type PaymentRequest');
        expect(tsOutLocal).not.toContain('export type PaymentRequest');
        expect(tsOut).toContain('id: string;');
        expect(tsOut).toContain('amount: number;');
        // Nullable field becomes union with null
        expect(tsOut).toContain('customer: Customer | null;');
        // Non-null nested scalar
        expect(tsOut).toContain('email: string;');
        // Unmapped scalar falls back to unknown
        expect(tsOut).toContain('custom: unknown;');
        // Debug comments include original GraphQL type
        expect(tsOut).toContain('// GraphQL: CustomScalar!');
    });
    it('renders readonly fields and lists when immutableTypes is set', () => {
        const schema = buildSchema(`
            type Query {
                invoices: [Invoice!]!
            }

            type Invoice {
                id: ID!
                lines: [InvoiceLine!]!
                tags: [String]
            }

            type InvoiceLine {
                amount: Int
            }
        `);

        const root = schema.getType('Invoice');
        if (!root || Array.isArray(root)) throw new Error('Missing Invoice type');

        const types = collectReachableTypes(schema, [root as any]);
        const immutable = renderTsFromSchema(types, { immutableTypes: true, includeGraphqlTypeComments: true });
        const mutable = renderTsFromSchema(types);

        expect(immutable).toContain('readonly id: string; // GraphQL: ID!');
        expect(immutable).toContain('readonly lines: ReadonlyArray<InvoiceLine>;');
        expect(immutable).toContain('readonly tags: ReadonlyArray<string | null> | null;');
        expect(immutable).toContain('readonly amount: number | null;');
        expect(immutable).not.toMatch(/[^y]Array</);

        expect(mutable).toContain('lines: Array<InvoiceLine>;');
        expect(mutable).not.toContain('readonly');
    });

    describe('one module per type', () => {
        const schema = buildSchema(`
            type Query { orders: [Order!]! }
            scalar numeric
            enum Status { open closed }
            union Party = Customer | Vendor
            type Order {
                id: ID!
                amount: numeric
                status: Status!
                party: Party
                lines: [Line!]!
                parent: Order
            }
            type Line { order: Order! qty: Int }
            type Customer { name: String! }
            type Vendor { name: String }
        `);
        const type = (name: string) => {
            const t = schema.getType(name);
            if (!t) throw new Error(`Missing ${name}`);
            return t;
        };
        const importPath = (name: string) => `./${name}`;

        it('lists the non-scalar types a type refers to, without itself', () => {
            expect(referencedTypeNames(type('Order'))).toEqual(['Line', 'Party', 'Status']);
            expect(referencedTypeNames(type('Party'))).toEqual(['Customer', 'Vendor']);
            expect(referencedTypeNames(type('Customer'))).toEqual([]);
        });

        it('renders an exported declaration that imports what it refers to', () => {
            expect(renderTypeModule(type('Order'), importPath, {
                immutableTypes: true,
                scalars: { numeric: 'string' }
            })).toBe([
                '// This file is auto-generated by `dtv typegen`.',
                '// Do not edit manually.',
                '',
                "import type { Line } from './Line';",
                "import type { Party } from './Party';",
                "import type { Status } from './Status';",
                '',
                'export type Order = {',
                '    readonly id: string;',
                '    readonly amount: string | null;',
                '    readonly status: Status;',
                '    readonly party: Party | null;',
                '    readonly lines: ReadonlyArray<Line>;',
                '    readonly parent: Order | null;',
                '};',
                ''
            ].join('\n'));
        });

        it('declares the same type a single module of all types declares', () => {
            const module = renderTypeModule(type('Line'), importPath, { includeGraphqlTypeComments: true });
            const all = renderTsFromSchema(collectReachableTypes(schema, [type('Order')]), { includeGraphqlTypeComments: true });
            const declaration = module?.slice(module.indexOf('export type'));
            expect(all).toContain(declaration?.trimEnd());
        });

        it('renders enums and unions, and nothing for a scalar', () => {
            expect(renderTypeModule(type('Status'), importPath)).toContain("export type Status = 'open' | 'closed';");
            expect(renderTypeModule(type('Party'), importPath)).toContain('export type Party = Customer | Vendor;');
            expect(renderTypeModule(type('numeric'), importPath)).toBeNull();
        });
    });
});
